"""Deterministic JSON output postprocessing for Verqen-T1.

Converts model output tensors into typed, deterministic JSON response dictionaries.
NEVER generated by the neural model itself.
"""

from __future__ import annotations

import math
from typing import Any
import torch


def compute_raw_confidence(probs: torch.Tensor, question_type: str) -> float:
    """Compute normalized-entropy confidence proxy.

    For K classes:
        H(p) = -sum(p_i * log(p_i))
        confidence = 1 - H(p) / log(K)  clamped to [0, 1]
    For binary Noul:
        confidence = max(P(true), P(false))
    """
    if question_type == "noul":
        # binary decision
        if probs.numel() == 2:
            return float(torch.max(probs).item())
        p = float(probs[0].item())
        return float(max(p, 1.0 - p))

    k = probs.size(-1)
    if k <= 1:
        return 1.0

    probs_clamped = torch.clamp(probs, min=1e-12, max=1.0)
    entropy = -torch.sum(probs_clamped * torch.log(probs_clamped), dim=-1)
    max_entropy = math.log(k)
    conf = 1.0 - (entropy.item() / max_entropy)
    return float(max(0.0, min(1.0, conf)))


def postprocess_choice(
    probs: torch.Tensor,
    options: list[str],
    option_mask: torch.Tensor | None = None,
    abstain_threshold: float | None = None,
) -> dict[str, Any]:
    """Convert Choice probabilities to deterministic JSON contract.

    Contract:
    {
      "type": "choice",
      "selected": "billing",
      "probabilities": {
        "billing": 0.84,
        "technical": 0.11,
        "account": 0.05
      },
      "confidence_raw": 0.72,
      "abstained": false
    }
    """
    n_opts = len(options)
    p_valid = probs[:n_opts]

    # Ensure normalization over valid options
    s = p_valid.sum()
    if s > 0:
        p_valid = p_valid / s
    else:
        p_valid = torch.full_like(p_valid, 1.0 / n_opts)

    prob_dict = {
        opt: round(float(p_valid[i].item()), 4)
        for i, opt in enumerate(options)
    }

    best_idx = int(torch.argmax(p_valid).item())
    selected = options[best_idx]
    confidence_raw = round(compute_raw_confidence(p_valid, "choice"), 4)

    abstained = False
    if "<ABSTAIN>" in options and selected == "<ABSTAIN>":
        abstained = True
    elif abstain_threshold is not None and confidence_raw < abstain_threshold:
        abstained = True

    return {
        "type": "choice",
        "selected": selected,
        "probabilities": prob_dict,
        "confidence_raw": confidence_raw,
        "abstained": abstained,
    }


def postprocess_noul(
    probs: torch.Tensor,
    abstain_threshold: float | None = None,
) -> dict[str, Any]:
    """Convert Noul (binary) probabilities to deterministic JSON contract.

    Contract:
    {
      "type": "noul",
      "value": true,
      "probabilities": {
        "false": 0.08,
        "true": 0.92
      },
      "confidence_raw": 0.92,
      "abstained": false
    }
    """
    if probs.numel() == 2:
        p_false = float(probs[0].item())
        p_true = float(probs[1].item())
    elif probs.numel() == 1:
        p_true = float(probs[0].item())
        p_false = 1.0 - p_true
    else:
        p_false = 0.5
        p_true = 0.5

    total = p_false + p_true
    if total > 0:
        p_false /= total
        p_true /= total

    value = bool(p_true >= 0.5)
    confidence_raw = round(float(max(p_true, p_false)), 4)

    abstained = False
    if abstain_threshold is not None and abs(p_true - 0.5) < abstain_threshold:
        abstained = True

    return {
        "type": "noul",
        "value": value,
        "probabilities": {
            "false": round(p_false, 4),
            "true": round(p_true, 4),
        },
        "confidence_raw": confidence_raw,
        "abstained": abstained,
    }


def postprocess_score(
    probs: torch.Tensor,
    options: list[str] | None = None,
    expected_score: float | None = None,
    abstain_threshold: float | None = None,
) -> dict[str, Any]:
    """Convert Score probabilities to deterministic JSON contract.

    Contract:
    {
      "type": "score",
      "expected_score": 2.19,
      "selected_level": 2,
      "probabilities": {
        "0": 0.01,
        "1": 0.09,
        "2": 0.60,
        "3": 0.30
      },
      "confidence_raw": 0.55,
      "abstained": false
    }
    """
    k = len(options) if options else probs.size(-1)
    p_valid = probs[:k]
    s = p_valid.sum()
    if s > 0:
        p_valid = p_valid / s
    else:
        p_valid = torch.full_like(p_valid, 1.0 / k)

    if expected_score is None:
        idx_tensor = torch.arange(k, dtype=torch.float32, device=probs.device)
        exp_s = float((p_valid * idx_tensor).sum().item())
    else:
        exp_s = float(expected_score)

    selected_level = int(torch.argmax(p_valid).item())

    # Format keys as string index or option name
    prob_dict = {}
    for i in range(k):
        key = str(i) if not options else options[i]
        prob_dict[key] = round(float(p_valid[i].item()), 4)

    confidence_raw = round(compute_raw_confidence(p_valid, "score"), 4)

    abstained = False
    if abstain_threshold is not None and confidence_raw < abstain_threshold:
        abstained = True

    return {
        "type": "score",
        "expected_score": round(exp_s, 2),
        "selected_level": selected_level,
        "probabilities": prob_dict,
        "confidence_raw": confidence_raw,
        "abstained": abstained,
    }
